#!/usr/bin/env python3
"""Runs tools/drone-install.py against fake drones and checks each run against
golden expectations: exit code, the drone's mabur.toml afterwards, every path
the run changed on the drone (with what it now holds) and the backup folder it
left on the PC.

A fake drone is a directory tree. A stub `ssh` first on PATH runs the
installer's remote commands with bash after rewriting the drone's absolute
paths into that tree; stubs stand in for fw_printenv, lsusb, lsmod, df, pidof,
reboot and the module tools. PATH holds only the stub directory (the stubs plus
links to the host tools the remote scripts use, never ssh or scp), so a run can
never reach a real drone, and every scenario checks that the stub was called.

  drone_install_test.py                 run every scenario
  drone_install_test.py NAME...         run only these
  drone_install_test.py --show NAME...  print what NAME produces now, in the
                                        golden format, to review a change

Needs python3 and bash only; runs offline.
"""
