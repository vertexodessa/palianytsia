def build_bin(bindir):
    bash = shutil.which("bash")
    bindir.mkdir()
    for tool in HOST_TOOLS:
        found = shutil.which(tool)
        if found is None:
            raise SystemExit(f"host tool missing: {tool}")
        (bindir / tool).symlink_to(found)
    (bindir / "ssh").write_text(FAKE_SSH.replace("@BASH@", bash))
    for k, v in STUBS.items():
        (bindir / k).unlink(missing_ok=True)
        (bindir / k).write_text(f"#!{bash}\n{v}\n")
    for f in bindir.iterdir():
        if not f.is_symlink():
            f.chmod(f.stat().st_mode | stat.S_IEXEC)


def run_one(sc, base):
    work = Path(tempfile.mkdtemp(prefix="drone-install-", dir=base))
    root, pkg, cwd = work / "root", work / "pkg", work / "cwd"
    root.mkdir()
    cwd.mkdir()
    make_drone(root, **sc["drone"])
    if sc["pkg"] is False:
        pkg.mkdir()
    else:
        make_package(pkg, **sc["pkg"])
    before = snapshot(root)
    bindir = base / "bin"
    path = str(bindir)
    if Path(shutil.which("ssh", path=path)).parent != bindir:
        raise SystemExit("ssh on the test PATH is not the stub")
    env = {"PATH": path, "ROOT": str(root), "HOME": str(work), "LC_ALL": "C", **sc["env"]}
    argv = [a.replace("PKG", str(pkg)) for a in sc["argv"]]
    # The installer sleeps up to 100 s waiting for a reboot; time stands still here.
    boot = (
        "import sys,time,runpy;time.sleep=lambda s:None;"
        f"sys.argv={['install.py', *argv]!r};runpy.run_path({str(INSTALLER)!r},run_name='__main__')"
    )
    p = subprocess.run([sys.executable, "-I", "-c", boot], cwd=cwd, env=env, stdin=subprocess.DEVNULL,
                       capture_output=True, text=True, timeout=60)
    after = snapshot(root)
    changes = {}
    for k in sorted(set(before) | set(after)):
        if k not in after:
            changes[k] = "deleted"
        elif before.get(k) != after[k]:
            changes[k] = "dir" if after[k] == "dir" else describe(after[k])
    backups = sorted(cwd.iterdir())
    if len(backups) > 1:
        raise AssertionError(f"{len(backups)} backup folders")
    backup = None
    if backups:
        backup = {f.name: describe(f.read_bytes()) for f in sorted(backups[0].iterdir())}
    toml = root / "etc/mabur.toml"
    log = root / ".fake-log"
    result = dict(
        rc=p.returncode,
        toml=toml.read_bytes().decode() if toml.exists() else None,
        changes=changes,
        backup=backup,
        # The fake drone's paths read as the drone's own, the rest of the run
        # directory as WORK.
        output=(p.stdout + p.stderr).replace(str(root), "").replace(str(work), "WORK").replace(str(INSTALLER), "install.py"),
        ssh_calls=len(log.read_text().splitlines()) if log.exists() else 0,
    )
    shutil.rmtree(work)
    return result


def check(sc, res):
    """The list of mismatches between a result and its scenario's golden data."""
    exp, bad = sc["expect"], []
    if res["ssh_calls"] == 0:
        bad.append("the stub ssh was never called")
    for key in ("rc", "toml", "changes", "backup"):
        if res[key] != exp[key]:
            bad.append(f"{key}: expected {exp[key]!r}\n      got      {res[key]!r}")
    for text in exp.get("says", ()):
        if text not in res["output"]:
            bad.append(f"output lacks {text!r}")
    return bad


def show(sc, res):
    print(f"    S({sc['name']!r}, ...,")
    for key in ("rc", "toml", "changes", "backup"):
        print(f"      {key}={res[key]!r},")
    print("    ),")
    print("    # output:\n" + "\n".join("    #   " + line for line in res["output"].splitlines()))


def main():
    args = sys.argv[1:]
    showing = bool(args) and args[0] == "--show"
    names = args[1:] if showing else args
    chosen = [sc for sc in SCENARIOS if not names or sc["name"] in names]
    unknown = set(names) - {sc["name"] for sc in chosen}
    if unknown:
        raise SystemExit(f"no such scenario: {', '.join(sorted(unknown))}")
    t0 = time.monotonic()
    with tempfile.TemporaryDirectory(prefix="drone-install-test-") as tmp:
        base = Path(tmp)
        build_bin(base / "bin")
        with concurrent.futures.ThreadPoolExecutor(max_workers=min(8, os.cpu_count() or 1)) as pool:
            results = list(pool.map(lambda sc: run_one(sc, base), chosen))
    failed = xfailed = 0
    for sc, res in zip(chosen, results):
        if showing:
            show(sc, res)
            continue
        bad = check(sc, res)
        if sc["xfail"]:
            if bad:
                print(f"xfail {sc['name']}: {sc['xfail']}")
                xfailed += 1
                continue
            bad = [f"passes but is marked as an expected failure ({sc['xfail']}); drop the mark"]
        if bad:
            failed += 1
            print(f"FAIL  {sc['name']}")
            for b in bad:
                print(f"      {b}")
            print("      output:\n" + "\n".join("        " + line for line in res["output"].splitlines()))
        else:
            print(f"ok    {sc['name']}")
    if showing:
        return 0
    ok = len(chosen) - failed - xfailed
    print(f"{ok}/{len(chosen)} scenarios ok, {xfailed} expected failures, {failed} failed"
          f" in {time.monotonic() - t0:.1f} s")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
