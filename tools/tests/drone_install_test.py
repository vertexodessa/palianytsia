BY_SHA = {hashlib.sha256(v).hexdigest(): k for k, v in NAMED.items()}


def as_bytes(text):
    return text.encode() if isinstance(text, str) else text


def describe(data):
    """A file's content as golden data: a fixture name, short text, or a sha."""
    name = BY_SHA.get(hashlib.sha256(data).hexdigest())
    if name or not data:
        return name or ""
    for k, v in NAMED.items():
        if data.startswith(v):
            return f"{k} + {data[len(v):]!r}"
        if v.startswith(data):
            return f"{k} cut to {len(data)} bytes"
    try:
        if len(data) <= 600:
            return data.decode()
    except UnicodeDecodeError:
        pass
    return "sha256:" + hashlib.sha256(data).hexdigest()[:16]


def snapshot(root):
    out = {}
    for p in sorted(root.rglob("*")):
        rel = str(p.relative_to(root))
        if rel.startswith(".fake-") or rel == ".down":
            continue
        out[rel] = "dir" if p.is_dir() else p.read_bytes()
    return out


def make_drone(root, bin_=BIN_OLD, cfg=CFG_KEY, wrapper="S96mabur", stock=(), ls=LS, ls_orig=None,
               init_off=(), module=False, log=True, sensors=()):
    for d in ("usr/bin", "etc/init.d", "tmp", "lib/modules/5.10/sigmastar", "lib/modules/5.10/extra", "overlay", "rom"):
        (root / d).mkdir(parents=True, exist_ok=True)
    (root / ".fake-drone").touch()
    if bin_ is not None:
        (root / "usr/bin/maburd").write_bytes(bin_)
    if cfg is not None:
        (root / "etc/mabur.toml").write_bytes(as_bytes(cfg))
    for s in ((wrapper,) if wrapper else ()) + tuple(stock):
        p = root / "etc/init.d" / s
        p.write_bytes(INIT)
        p.chmod(0o755)
    if init_off:
        (root / "etc/init.d.off").mkdir()
        for s in init_off:
            (root / "etc/init.d.off" / s).write_bytes(INIT)
    (root / "usr/bin/load_sigmastar").write_bytes(as_bytes(ls))
    if ls_orig is not None:
        (root / "usr/bin/load_sigmastar.palianytsia").write_bytes(ls_orig)
    if module:
        (root / "lib/modules/5.10/sigmastar/sensor_imx415_star6e.ko").write_bytes(KO)
    if sensors:
        (root / "etc/sensors").mkdir()
        for name in sensors:
            (root / "etc/sensors" / name).write_bytes(b"t")
    (root / "lib/modules/5.10/extra/8812eu.ko").write_bytes(b"k")
    if log:
        (root / "tmp/mabur.log").write_text("maburd: build mabur abc\n")


def make_package(d, bin_=BIN_NEW, cfg=CFG_KEY, init=INIT, mod=None, backup=False):
    d.mkdir(parents=True)
    (d / "maburd").write_bytes(bin_)
    if cfg is not None:
        (d / "mabur.toml").write_bytes(as_bytes(cfg))
    if init is not None:
        (d / "S96mabur").write_bytes(init)
    if mod is not None:
        (d / "sensor_imx415_star6e.ko").write_bytes(mod)
    if backup:
        (d / ".drone-backup").touch()


